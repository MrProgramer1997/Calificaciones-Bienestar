
create extension if not exists pgcrypto with schema extensions;
create table public.cargos_bienestar (
 id smallint generated by default as identity primary key,
 slug text not null unique,
 nombre text not null,
 activo boolean not null default true,
 orden smallint not null unique
);
create table public.areas_colaboradores (
 id smallint generated by default as identity primary key,
 nombre text not null unique,
 activo boolean not null default true
);
create table public.valoraciones (
 id uuid primary key default gen_random_uuid(),
 cargo_id smallint not null references public.cargos_bienestar(id),
 area_id smallint not null references public.areas_colaboradores(id),
 calificacion smallint not null check(calificacion between 1 and 5),
 comentario text check (char_length(comentario)<=2000),
 creado_en timestamptz not null default now()
);
create index valoraciones_cargo_fecha_idx on public.valoraciones (cargo_id, creado_en desc);
create index valoraciones_area_fecha_idx on public.valoraciones (area_id, creado_en desc);
create table public.admin_usuarios (
 user_id uuid primary key references auth.users(id) on delete cascade,
 nombre_usuario text not null unique,
 activo boolean not null default true,
 creado_en timestamptz not null default now()
);
