alter table public.cargos_bienestar enable row level security;
alter table public.areas_colaboradores enable row level security;
alter table public.valoraciones enable row level security;
alter table public.admin_usuarios enable row level security;
grant usage on schema public to anon,authenticated;
grant select on public.cargos_bienestar,public.areas_colaboradores to anon,authenticated;
grant insert on public.valoraciones to anon,authenticated;
grant select on public.valoraciones to authenticated;
grant select on public.admin_usuarios to authenticated;
create policy cargos_lectura on public.cargos_bienestar for select to anon, authenticated using (activo);
create policy areas_lectura on public.areas_colaboradores for select to anon, authenticated using (activo);
create policy valoraciones_insertar on public.valoraciones for insert to anon, authenticated
 with check (
 exists(select 1 from public.cargos_bienestar c where c.id=cargo_id and c.activo)
 and exists(select 1 from public.areas_colaboradores a where a.id=area_id and a.activo)
 );
create policy valoraciones_admin_lectura on public.valoraciones for select to authenticated using (
 exists (select 1 from public.admin_usuarios u where u.user_id=(select auth.uid()) and u.activo)
);
create policy admin_identidad on public.admin_usuarios for select to authenticated using (user_id=(select auth.uid()));

